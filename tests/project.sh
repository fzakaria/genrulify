# Project mode converts a derivation whose source is a directory someone is
# working in. The source tree is part of the graph, so a rule lists the
# project's own files and a rebuild sees an edit.
#
# Recording needs Rewind, so the test makes a project recording by hand
# from the example: it declares a source tree that holds the header the
# first dd reads, and says that the dd read it. Then it checks the graph,
# the passes, the build files written into a project directory, and the
# check that a directory still holds the recorded source.
set -eu
compiler=$1
data=$2
scratch=$(mktemp -d)
trap 'chmod -R u+w "$scratch"; rm -rf "$scratch"' EXIT

source=/nix/store/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa-source
header=cb94740ad765d0c3cb3742959e2f7556d4c7adb712660bfbacb1ba2c6f50e671
cp -r "$data/example" "$scratch/recording"
chmod -R u+w "$scratch/recording"
sed -i "s|^ \"run\":| \"source\": \"$source\",\n \"run\":|" "$scratch/recording/recording.json"
sed -i "0,/\"reads\": \[\],/s||\"reads\": [\"$source/header.txt\"],|" "$scratch/recording/recording.json"
cat > "$scratch/recording/states/source.json" <<JSON
[
 {"content": "", "kind": "dir", "mode": 365, "mtime": 1, "path": "$source"},
 {"content": "$header", "kind": "file", "mode": 292, "mtime": 1, "path": "$source/header.txt"}
]
JSON

# The source tree is one literal, defined before anything else, and the dd
# that read the header takes that entry as an operand.
"$compiler" import "$scratch/recording" > "$scratch/graph.mlir"
grep -q '%source_717:2 = splice.literal "source" at 717' "$scratch/graph.mlir"
grep -q 'splice.exec "dd" at 735(%sandbox_717, %source_717#0, %source_717#1)' "$scratch/graph.mlir"

# The first dd wrote the header's bytes to another path. In a recorded
# build that makes the dd a copy. Here the header is a source someone may
# edit, and what the dd writes then is for the dd to say, so the passes
# leave the command in.
"$compiler" opt "$scratch/graph.mlir" > "$scratch/opt.mlir"
grep -q 'splice.exec "dd" at 735(%sandbox_717, %source_717#0, %source_717#1)' "$scratch/opt.mlir"
if grep -q 'splice.copy "dd" at 735' "$scratch/opt.mlir"; then
    exit 1
fi

# Build files are written into the project. The rule of the command that
# read the header lists the project's own file, everything else genrulify
# wrote is under genrulify/, and the files say who wrote them.
mkdir "$scratch/project"
printf 'header\n' > "$scratch/project/header.txt"
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
cd "$scratch/project"
head -n 1 BUILD.bazel | grep -q '^# Generated by genrulify'
head -n 1 BUCK | grep -q '^# Generated by genrulify'
grep -q 'load(":genrulify/genrulify.bzl"' BUILD.bazel
grep -q 'load("//genrulify:genrulify.buck.bzl"' BUCK
rule() {
    sed -n "/name = \"$2\"/,/^)/p" "$1"
}
rule BUILD.bazel s735_dd | grep -q '":header.txt",'
rule BUILD.bazel s764_dd | grep -q '":s735_dd/build/bundle",'
rule BUILD.bazel s764_dd | grep -q '":genrulify/actions/s764_dd.manifest",'
rule BUILD.bazel s764_dd | grep -q '"./genrulify/sandbox.sh --in genrulify --in . --in $(RULEDIR) --out $(RULEDIR)"'
rule BUCK s735_dd | grep -q '"header.txt",'
rule BUCK s764_dd | grep -q '"\$SRCDIR/genrulify/sandbox.sh --in \$SRCDIR/genrulify --in \$SRCDIR --out \${OUT%/\*}"'
test -x genrulify/sandbox.sh
test "$(cat genrulify/source.txt)" = "$source"
test ! -e sandbox.sh
test ! -e actions

# A project's archive is whatever the sources now give, so its rule is
# given no digest to hold the archive to.
rule BUILD.bazel archive | grep -q 'pack /nix/store/[a-z0-9]*-genrulify-example"'

# The manifest stages the project's file where the command read it, at
# the path the header had in the store.
grep -q "$source/header.txt.*header.txt$" genrulify/actions/s735_dd.manifest

# An edited source must not fail a rule, so the rules of a project trust
# what a command leaves. The rules of a recorded build do not.
grep -q '^_TRUST = True$' genrulify/genrulify.bzl
grep -q '^_TRUST = True$' genrulify/genrulify.buck.bzl
"$compiler" import "$data/example" > "$scratch/plain.mlir"
"$compiler" emit "$data/example" "$scratch/plain.mlir" "$scratch/plain"
grep -q '^_TRUST = False$' "$scratch/plain/genrulify.bzl"
if grep -q 'Generated by genrulify' "$scratch/plain/BUILD.bazel"; then
    exit 1
fi

# Converting again replaces what genrulify wrote and keeps the project's
# file.
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
test "$(cat header.txt)" = header

# A build file that somebody else wrote is left alone.
printf 'cc_binary(name = "mine")\n' > BUILD.bazel
if "$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'BUILD.bazel was not written by genrulify' "$scratch/error"
grep -q 'mine' BUILD.bazel

# genrulify keeps its own files in the project's genrulify/ directory and
# replaces that directory on every conversion. A directory of that name
# that genrulify did not write is somebody's work and is left alone.
rm BUILD.bazel
mkdir "$scratch/taken" "$scratch/taken/genrulify"
printf 'header\n' > "$scratch/taken/header.txt"
printf 'mine\n' > "$scratch/taken/genrulify/notes.txt"
if "$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/taken" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'genrulify was not written by genrulify' "$scratch/error"
test "$(cat "$scratch/taken/genrulify/notes.txt")" = mine

# A file with the name of one genrulify writes does not make the directory
# genrulify's. Only the mark genrulify leaves in the directory does.
printf '/nix/store/mine\n' > "$scratch/taken/genrulify/source.txt"
if "$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/taken" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'genrulify was not written by genrulify' "$scratch/error"
test "$(cat "$scratch/taken/genrulify/notes.txt")" = mine

# A rule finds a file by name, among genrulify's files first. A source
# file with the name of one of those, such as closure.txt, would be read
# as genrulify's file, so the conversion is refused and names the file.
cp -r "$scratch/recording" "$scratch/clash"
sed -i 's|/header.txt|/closure.txt|' "$scratch/clash/recording.json" "$scratch/clash/states/source.json"
"$compiler" import "$scratch/clash" > "$scratch/clash.mlir"
"$compiler" opt "$scratch/clash.mlir" > "$scratch/clash.opt.mlir"
mkdir "$scratch/clashing"
printf 'header\n' > "$scratch/clashing/closure.txt"
if "$compiler" emit "$scratch/clash" "$scratch/clash.opt.mlir" "$scratch/clashing" 2> "$scratch/error"; then
    exit 1
fi
grep -q "the project's closure.txt has the name of a file genrulify keeps" "$scratch/error"

# A conversion that fails leaves the last one working: the files genrulify
# wrote before are all still there, and so are the build files that name
# them. Here the converted project is given the recording that is refused.
cd "$scratch/project"
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
cp BUILD.bazel "$scratch/BUILD.before"
printf 'header\n' > closure.txt
if "$compiler" emit "$scratch/clash" "$scratch/clash.opt.mlir" "$scratch/project" 2> "$scratch/error"; then
    exit 1
fi
test -x genrulify/sandbox.sh
test -e genrulify/actions/s764_dd.manifest
cmp BUILD.bazel "$scratch/BUILD.before"
test "$(find . -maxdepth 1 -name '.genrulify.*' | wc -l)" = 0

# A conversion that succeeds leaves nothing of the way it was put in
# place: no staging directory, no directory of the last conversion, and
# no build file under its staging name.
rm closure.txt
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
test "$(find . -maxdepth 1 -name '.genrulify.*' | wc -l)" = 0
test "$(find genrulify -maxdepth 1 -name 'build-file.*' | wc -l)" = 0
head -n 1 BUILD.bazel | grep -q '^# Generated by genrulify'

# A directory holds a source tree when every file of the tree is in the
# directory with the same bytes. The directory may hold more. A file that
# differs or is missing is named.
mkdir -p "$scratch/tree/sub" "$scratch/work/sub"
printf 'one\n' > "$scratch/tree/a.c"
printf 'two\n' > "$scratch/tree/sub/b.h"
cp -r "$scratch/tree/." "$scratch/work/"
printf 'extra\n' > "$scratch/work/notes.txt"
"$compiler" same-source "$scratch/tree" "$scratch/work"
printf 'changed\n' > "$scratch/work/sub/b.h"
if "$compiler" same-source "$scratch/tree" "$scratch/work" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'sub/b.h differs' "$scratch/error"
rm "$scratch/work/sub/b.h"
if "$compiler" same-source "$scratch/tree" "$scratch/work" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'sub/b.h is missing' "$scratch/error"

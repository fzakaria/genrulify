# Project mode converts a derivation whose source is a directory someone is
# working in. The source tree is part of the graph, so a rule lists the
# project's own files and a rebuild sees an edit.
#
# Recording needs Rewind, so the test makes a project recording by hand
# from the example: it declares a source tree that holds the header the
# first dd reads, and says that the dd read it. Then it checks the graph,
# the passes, the build files written into a project directory, and the
# check that a directory still holds the recorded source.
set -eu
compiler=$1
data=$2
scratch=$(mktemp -d)
trap 'chmod -R u+w "$scratch"; rm -rf "$scratch"' EXIT

source=/nix/store/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa-source
header=cb94740ad765d0c3cb3742959e2f7556d4c7adb712660bfbacb1ba2c6f50e671
cp -r "$data/example" "$scratch/recording"
chmod -R u+w "$scratch/recording"
sed -i "s|^ \"run\":| \"source\": \"$source\",\n \"run\":|" "$scratch/recording/recording.json"
sed -i "0,/\"reads\": \[\],/s||\"reads\": [\"$source/header.txt\"],|" "$scratch/recording/recording.json"
cat > "$scratch/recording/states/source.json" <<JSON
[
 {"content": "", "kind": "dir", "mode": 365, "mtime": 1, "path": "$source"},
 {"content": "$header", "kind": "file", "mode": 292, "mtime": 1, "path": "$source/header.txt"}
]
JSON

# The source tree is one literal, defined before anything else, and the dd
# that read the header takes that entry as an operand.
"$compiler" import "$scratch/recording" > "$scratch/graph.mlir"
grep -q '%source_717:2 = splice.literal "source" at 717' "$scratch/graph.mlir"
grep -q 'splice.exec "dd" at 735(%sandbox_717, %source_717#0, %source_717#1)' "$scratch/graph.mlir"

# The first dd wrote the header's bytes to another path. In a recorded
# build that makes the dd a copy. Here the header is a source someone may
# edit, and what the dd writes then is for the dd to say, so the passes
# leave the command in.
# The dd, and every command after it that depends on the header, is
# marked `watched`: its rule runs in every build of the project.
"$compiler" opt "$scratch/graph.mlir" > "$scratch/opt.mlir"
grep -q 'splice.exec "dd" at 735 watched(%sandbox_717, %source_717#0, %source_717#1)' "$scratch/opt.mlir"
test "$(grep -c 'splice.exec "dd" at [0-9]* watched(' "$scratch/opt.mlir")" = 3
if grep -q 'splice.copy "dd" at 735' "$scratch/opt.mlir"; then
    exit 1
fi

# The rules are written into the project's genrulify/ directory, as a
# function in a file for each build system, with everything else
# genrulify wrote. The project's own build files only load that function
# and call it, so a build file somebody wrote by hand can do the same and
# keep its own rules. The rule of the command that read the header lists
# the project's own file, and the files say who wrote them.
mkdir "$scratch/project"
printf 'header\n' > "$scratch/project/header.txt"
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
cd "$scratch/project"
head -n 1 BUILD.bazel | grep -q '^# Generated by genrulify'
head -n 1 BUCK | grep -q '^# Generated by genrulify'
grep -q '^load(":genrulify/targets.bzl", "genrulify_targets")$' BUILD.bazel
grep -q '^load("//genrulify:targets.buck.bzl", "genrulify_targets")$' BUCK
for file in BUILD.bazel BUCK; do
    grep -q '^genrulify_targets()$' "$file"
    test "$(grep -c . "$file")" = 3
done
bazel_rules=genrulify/targets.bzl
buck_rules=genrulify/targets.buck.bzl
head -n 1 "$bazel_rules" | grep -q '^# Generated by genrulify'
grep -q '^load(":genrulify/genrulify.bzl"' "$bazel_rules"
grep -q '^load("//genrulify:genrulify.buck.bzl"' "$buck_rules"
grep -q '^def genrulify_targets():$' "$bazel_rules"
grep -q '^def genrulify_targets():$' "$buck_rules"
rule() {
    sed -n "/name = \"$2\"/,/^ *)/p" "$1"
}
rule "$bazel_rules" s735_dd | grep -q '":header.txt",'
rule "$bazel_rules" s764_dd | grep -q '":s735_dd/build/bundle",'
rule "$bazel_rules" s764_dd | grep -q '":genrulify/actions/s764_dd.manifest",'
rule "$bazel_rules" s764_dd | grep -q '"./genrulify/sandbox.sh --in genrulify --in . --in $(RULEDIR) --out $(RULEDIR)"'
rule "$buck_rules" s735_dd | grep -q '"header.txt",'
rule "$buck_rules" s764_dd | grep -q '":s735_dd\[build/bundle\]",'
rule "$buck_rules" s764_dd | grep -q '"\$SRCDIR/genrulify/sandbox.sh --in \$SRCDIR/genrulify --in \$SRCDIR --out \$OUTDIR"'
test -x genrulify/sandbox.sh
test "$(cat genrulify/source.txt)" = "$source"
test ! -e sandbox.sh
test ! -e actions

# A project's archive is whatever the sources now give, so its rule is
# given no digest to hold the archive to.
rule "$bazel_rules" archive | grep -q 'pack /nix/store/[a-z0-9]*-genrulify-example"'

# The manifest stages the project's file where the command read it, at
# the path the header had in the store, and says that the file is the
# project's own, so that it is staged with the executable bit it has now.
grep -q "$source/header.txt.*header.txt.@checkout$" genrulify/actions/s735_dd.manifest

# An edited source must not fail a rule, so a command that depends on the
# project's sources is trusted: its rule takes what the command leaves.
# Every dd here reads what the one before it wrote, and the first reads
# the header. A step that is given a file such a command wrote reads the
# file's mode from that command's stamp. The step that packs the archive
# starts no command and is not trusted.
rule "$bazel_rules" s735_dd | grep -q '"--name s735_dd --timeout [0-9]* --trust",'
rule "$buck_rules" s764_dd | grep -q '"--name s764_dd --timeout [0-9]* --trust",'
grep -q "/build/bundle.*s735_dd/build/bundle.s735_dd$" genrulify/actions/s764_dd.manifest
if rule "$bazel_rules" archive | grep -q -e '--trust'; then
    exit 1
fi
test "$(cat genrulify/outputs.txt)" = /nix/store/l1dx8g9mr73bdp8y6i2yp92xprmz8xzg-genrulify-example
rule "$bazel_rules" s735_dd | grep -q '":genrulify/outputs.txt",'

# A watched command whose results nothing reads is on no path to the
# archive, and a build system runs only what the archive needs. So the
# archive rule waits for the stamp of every such command, and the command
# gets to run and to fail. Here the output is emptied, which leaves the
# last dd with no reader.
sed 's|^\(  splice.output .*\)(%dd_782)|\1()|' "$scratch/opt.mlir" > "$scratch/unread.mlir"
mkdir "$scratch/unread"
printf 'header\n' > "$scratch/unread/header.txt"
"$compiler" emit "$scratch/recording" "$scratch/unread.mlir" "$scratch/unread"
rule "$scratch/unread/$bazel_rules" archive | grep -q '":s782_dd.ok",'
rule "$scratch/unread/$buck_rules" archive | grep -q '":s782_dd",'

# A watched command that has a reader is run for that reader, and the
# archive does not wait for it besides.
if rule "$scratch/unread/$bazel_rules" archive | grep -q '":s764_dd.ok",'; then
    exit 1
fi

# A command of a recorded build is held to the recording.
"$compiler" import "$data/example" > "$scratch/plain.mlir"
"$compiler" emit "$data/example" "$scratch/plain.mlir" "$scratch/plain"
if grep -q -e '--trust' "$scratch/plain/BUILD.bazel" "$scratch/plain/BUCK"; then
    exit 1
fi
test ! -e "$scratch/plain/outputs.txt"
if grep -q 'Generated by genrulify' "$scratch/plain/BUILD.bazel"; then
    exit 1
fi

# Converting again replaces what genrulify wrote and keeps the project's
# file.
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
test "$(cat header.txt)" = header

# A build file that somebody else wrote is left alone, and the conversion
# says which two lines make it build the converted targets. Once the file
# has them there is nothing to say.
printf 'cc_binary(name = "mine")\n' > BUILD.bazel
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project" 2> "$scratch/note"
test "$(cat BUILD.bazel)" = 'cc_binary(name = "mine")'
grep -q 'BUILD.bazel is not genrulify.s and was left as it is' "$scratch/note"
grep -q '^  load(":genrulify/targets.bzl", "genrulify_targets")$' "$scratch/note"
grep -q '^  genrulify_targets()$' "$scratch/note"
if grep -q 'BUCK' "$scratch/note"; then
    exit 1
fi
printf 'load(":genrulify/targets.bzl", "genrulify_targets")\ngenrulify_targets()\ncc_binary(name = "mine")\n' > BUILD.bazel
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project" 2> "$scratch/note"
test ! -s "$scratch/note"
grep -q 'mine' BUILD.bazel

# Bazel reads a package's build file as BUILD.bazel or as BUILD, and takes
# BUILD.bazel when both are there. A project whose own file is called
# BUILD must not be given a BUILD.bazel, which would hide every target the
# project had. The loader genrulify wrote on an earlier conversion goes,
# and the note is about the file that is the project's. Buck2 reads
# BUCK.v2 before BUCK in the same way.
rm BUILD.bazel
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
head -n 1 BUILD.bazel | grep -q '^# Generated by genrulify'
printf 'cc_binary(name = "mine")\n' > BUILD
printf 'export_file(name = "mine")\n' > BUCK.v2
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project" 2> "$scratch/note"
test ! -e BUILD.bazel
test ! -e BUCK
test "$(cat BUILD)" = 'cc_binary(name = "mine")'
grep -q 'project/BUILD is not genrulify.s and was left as it is' "$scratch/note"
grep -q 'project/BUCK.v2 is not genrulify.s and was left as it is' "$scratch/note"
rm BUILD BUCK.v2
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
head -n 1 BUCK | grep -q '^# Generated by genrulify'
printf 'cc_binary(name = "mine")\n' > BUILD.bazel

# genrulify keeps its own files in the project's genrulify/ directory and
# replaces that directory on every conversion. A directory of that name
# that genrulify did not write is somebody's work and is left alone.
rm BUILD.bazel
mkdir "$scratch/taken" "$scratch/taken/genrulify"
printf 'header\n' > "$scratch/taken/header.txt"
printf 'mine\n' > "$scratch/taken/genrulify/notes.txt"
if "$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/taken" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'genrulify was not written by genrulify' "$scratch/error"
test "$(cat "$scratch/taken/genrulify/notes.txt")" = mine

# A file with the name of one genrulify writes does not make the directory
# genrulify's. Only the mark genrulify leaves in the directory does.
printf '/nix/store/mine\n' > "$scratch/taken/genrulify/source.txt"
if "$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/taken" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'genrulify was not written by genrulify' "$scratch/error"
test "$(cat "$scratch/taken/genrulify/notes.txt")" = mine

# A rule finds a file by name, among genrulify's files first. A source
# file with the name of one of those, such as closure.txt, would be read
# as genrulify's file, so the conversion is refused and names the file.
cp -r "$scratch/recording" "$scratch/clash"
sed -i 's|/header.txt|/closure.txt|' "$scratch/clash/recording.json" "$scratch/clash/states/source.json"
"$compiler" import "$scratch/clash" > "$scratch/clash.mlir"
"$compiler" opt "$scratch/clash.mlir" > "$scratch/clash.opt.mlir"
mkdir "$scratch/clashing"
printf 'header\n' > "$scratch/clashing/closure.txt"
if "$compiler" emit "$scratch/clash" "$scratch/clash.opt.mlir" "$scratch/clashing" 2> "$scratch/error"; then
    exit 1
fi
grep -q "the project's closure.txt has the name of a file genrulify keeps" "$scratch/error"

# A file below a directory that has a build file of its own belongs to
# that package, and neither build system lets the root package name it by
# a path. The rules name such a file by its package, `//lib:header.txt`,
# and the conversion says what the package has to export, since its build
# file is the project's. A command still reads the file at its path in
# the project, which Bazel gives it anyway and which the Buck2 rule is
# told. Here the header is moved into lib/, which has both build files.
cp -r "$scratch/recording" "$scratch/nested"
sed -i "s|$source/header.txt|$source/lib/header.txt|" "$scratch/nested/recording.json" "$scratch/nested/states/source.json"
sed -i "s|^\[|[\n {\"content\": \"\", \"kind\": \"dir\", \"mode\": 365, \"mtime\": 1, \"path\": \"$source/lib\"},|" "$scratch/nested/states/source.json"
"$compiler" import "$scratch/nested" > "$scratch/nested.mlir"
"$compiler" opt "$scratch/nested.mlir" > "$scratch/nested.opt.mlir"
mkdir -p "$scratch/packages/lib"
printf 'header\n' > "$scratch/packages/lib/header.txt"
printf 'filegroup(name = "mine")\n' > "$scratch/packages/lib/BUILD.bazel"
printf 'filegroup(name = "mine")\n' > "$scratch/packages/lib/BUCK"
"$compiler" emit "$scratch/nested" "$scratch/nested.opt.mlir" "$scratch/packages" 2> "$scratch/note"
rule "$scratch/packages/$bazel_rules" s735_dd | grep -q '"//lib:header.txt",'
rule "$scratch/packages/$buck_rules" s735_dd | grep -q '"//lib:header.txt",'
rule "$scratch/packages/$buck_rules" s735_dd | grep -A 2 'foreign = \[' | grep -q '"//lib:header.txt",'
rule "$scratch/packages/$buck_rules" s735_dd | grep -A 2 'foreign_paths = \[' | grep -q '"lib/header.txt",'
if rule "$scratch/packages/$bazel_rules" s735_dd | grep -q 'foreign\|":lib/header.txt"'; then
    exit 1
fi
grep -q "lib/header.txt.*lib/header.txt.@checkout$" "$scratch/packages/genrulify/actions/s735_dd.manifest"
grep -q 'packages/lib/BUILD.bazel has to export' "$scratch/note"
grep -q '^  exports_files(\["header.txt"\])$' "$scratch/note"
grep -q 'packages/lib/BUCK has to export' "$scratch/note"
grep -q '^  export_file(name = "header.txt", visibility = \["PUBLIC"\])$' "$scratch/note"

# Once the package exports the file there is nothing to say.
printf 'exports_files(["header.txt"])\n' > "$scratch/packages/lib/BUILD.bazel"
printf 'export_file(name = "header.txt", visibility = ["PUBLIC"])\n' > "$scratch/packages/lib/BUCK"
"$compiler" emit "$scratch/nested" "$scratch/nested.opt.mlir" "$scratch/packages" 2> "$scratch/note"
test ! -s "$scratch/note"

# A conversion that fails leaves the last one working: the files genrulify
# wrote before are all still there, and so are the build files that name
# them. Here the converted project is given the recording that is refused.
cd "$scratch/project"
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
cp "$bazel_rules" "$scratch/rules.before"
printf 'header\n' > closure.txt
if "$compiler" emit "$scratch/clash" "$scratch/clash.opt.mlir" "$scratch/project" 2> "$scratch/error"; then
    exit 1
fi
test -x genrulify/sandbox.sh
test -e genrulify/actions/s764_dd.manifest
cmp "$bazel_rules" "$scratch/rules.before"
test "$(find . -maxdepth 1 -name '.genrulify.*' | wc -l)" = 0

# A conversion that succeeds leaves nothing of the way it was put in
# place: no staging directory and no directory of the last conversion.
rm closure.txt
"$compiler" emit "$scratch/recording" "$scratch/opt.mlir" "$scratch/project"
test "$(find . -maxdepth 1 -name '.genrulify.*' | wc -l)" = 0
head -n 1 BUILD.bazel | grep -q '^# Generated by genrulify'

# A directory holds a source tree when every file of the tree is in the
# directory with the same bytes. The directory may hold more. A file that
# differs or is missing is named.
mkdir -p "$scratch/tree/sub" "$scratch/work/sub"
printf 'one\n' > "$scratch/tree/a.c"
printf 'two\n' > "$scratch/tree/sub/b.h"
cp -r "$scratch/tree/." "$scratch/work/"
printf 'extra\n' > "$scratch/work/notes.txt"
"$compiler" same-source "$scratch/tree" "$scratch/work"
printf 'changed\n' > "$scratch/work/sub/b.h"
if "$compiler" same-source "$scratch/tree" "$scratch/work" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'sub/b.h differs' "$scratch/error"
rm "$scratch/work/sub/b.h"
if "$compiler" same-source "$scratch/tree" "$scratch/work" 2> "$scratch/error"; then
    exit 1
fi
grep -q 'sub/b.h is missing' "$scratch/error"

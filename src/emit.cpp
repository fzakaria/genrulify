// A file a rule reads: the target the file belongs to, which is the rule
// that wrote the file or the name recorded bytes are stored under, the
// file in the build system's tree, and the path the command sees the file
// at.
struct Input {
  std::string target;
  std::string artifact;
  std::string path;

  // Whether the file is one of the project's own sources, which a build
  // file names by the package the file belongs to.
  bool ofProject = false;
  auto operator<=>(const Input &) const = default;
};

// A shared library a link was given: the name the link knew the library
// by, which can be the name of a symlink to it, the file that holds the
// library, and whether another rule wrote that file.
struct Library {
  std::string name;
  Input file;
  bool generated = false;
};

// One rule: the files it reads, the files it writes, and the recorded
// command lines that turn one into the other.
struct Rule {
  std::string name;

  // The kind of rule the command was raised to, or empty, and the paths
  // the command names as its sources when it is a compile.
  std::string kind;
  std::set<std::string> sourcePaths;

  // Files the compiler wrote for the rule: the sandbox script and what it
  // shares between rules, and the rule's manifest.
  std::set<std::string> sources;

  // Bytes taken from the recording, which are files in the workspace.
  std::set<Input> recorded;

  // File versions written by other rules, and the rules whose stamp this
  // rule waits for because it uses a directory or a symlink they made.
  std::set<Input> generated;
  std::set<std::string> stamps;

  // The files this rule writes, and whether its last output is a NAR.
  std::vector<std::string> outputs;
  bool archive = false;

  // The step the rule's command was recorded at. A rule that runs no
  // command of its own, as the archive, has none.
  uint64_t step = 0;

  // Whether the rule runs nothing and stands for watched commands: the
  // ones in `stamps`, and the ones the target `after` stands for. On an
  // archive `after` is the target of that kind the archive waits for, or
  // empty. `fileAfter` is the same for the target that names the rule's
  // file.
  bool gate = false;
  std::string after;
  std::string fileAfter;

  // The guest path of the file the rule writes when it writes exactly
  // one, and the name that file is given as a target of its own, or
  // empty.
  std::string writes;
  std::string fileName;

  // The shared libraries of the workspace the command was given. A
  // program that is run from the build tree needs them where the loader
  // looks.
  std::vector<Library> libraries;

  std::vector<Arguments> arguments;
};

std::string quote(std::string_view value) { return Json(value).dump(); }

// A Starlark list of strings, one item per line, as an attribute's value.
std::string list(const Arguments &items) {
  if (items.empty()) {
    return "[]";
  }
  std::string text = "[\n";
  for (const auto &item : items) {
    absl::StrAppend(&text, kItemIndent, quote(item), ",\n");
  }
  return absl::StrCat(text, kAttributeIndent, "]");
}

// Quotes an argument the way a shell needs it typed.
std::string shellQuote(const std::string &argument) {
  static const std::regex plain("[A-Za-z0-9_@%+=:,./-]+");
  if (std::regex_match(argument, plain)) {
    return argument;
  }
  return absl::StrCat("'", absl::StrReplaceAll(argument, {{"'", "'\\''"}}),
                      "'");
}

// One line of a rule's command: recorded arguments, quoted for the shell.
// Bazel gives `$` a meaning of its own in a genrule's command, so there
// the line is quoted once more. A Buck2 rule writes its lines into a
// script as they are.
std::string commandLine(Backend backend, const Arguments &arguments) {
  Arguments words;
  for (const auto &argument : arguments) {
    words.push_back(shellQuote(argument));
  }
  const auto line = absl::StrJoin(words, " ");
  if (backend == Backend::Bazel) {
    return absl::StrReplaceAll(line, {{"$", "$$"}});
  }
  return line;
}

std::string stampFile(std::string_view target) {
  return absl::StrCat(target, kStampExtension);
}

// One attribute of a rule: `name = value`.
std::string attribute(std::string_view name, std::string_view value) {
  return absl::StrCat(name, " = ", value);
}

// Whether a guest path has the name of a shared library.
bool isSharedLibrary(const std::string &path) {
  static const std::regex name{std::string(kSharedLibraryName)};
  return std::regex_match(fs::path(path).filename().string(), name);
}

// The name of the rule a command is lowered to. A compile is a cc_object
// only when exactly one of its inputs is a source the command names:
// with none or several there is no `src` to write, and the command keeps
// the plain rule. The name is decided once so that both build files call
// a command the same thing.
std::string_view macroOf(const Rule &rule) {
  if (rule.archive) {
    return kArchiveRule;
  }
  if (rule.gate) {
    return kWatchedRule;
  }
  if (rule.kind.empty()) {
    return kRecordedRule;
  }
  if (rule.kind != kCcObject) {
    return rule.kind;
  }
  size_t named = 0;
  for (const auto *inputs : {&rule.recorded, &rule.generated}) {
    for (const auto &input : *inputs) {
      named += rule.sourcePaths.contains(input.path) ? 1 : 0;
    }
  }
  return named == 1 ? kCcObject : kRecordedRule;
}

// The rule that names the file a typed rule wrote: a program for a link
// that makes one, and a plain file for everything else.
std::string_view fileRuleOf(std::string_view macro) {
  return macro == kCcBinary || macro == kRustBinary ? kProgramRule
                                                    : kBuiltFileRule;
}

// The command of a rule as the lines of a list: where the sandbox script
// finds its inputs and puts its outputs, then the recorded command lines.
// The rule joins the lines with spaces.
std::string commandLines(Backend backend, const Rule &rule,
                         const Layout &layout) {
  std::string invocation(
      backend == Backend::Bazel
          ? (layout.project ? kBazelProjectInvocation : kBazelInvocation)
          : (layout.project ? kBuckProjectInvocation : kBuckInvocation));

  // In a shared workspace the script is told each place a file can be:
  // the package, the shared directory, what the package's rules wrote,
  // and for the archives of store paths the workspace's sources and
  // everything any rule wrote.
  if (layout.shared()) {
    invocation = absl::StrCat("./", kSharedDirectory, "/", kSandboxFile,
                              " --in ", layout.package, " --in ",
                              kSharedDirectory,
                              " --in $(RULEDIR) --in . --in $(BINDIR) --out "
                              "$(RULEDIR)");
  }
  Arguments lines{invocation};
  for (const auto &arguments : rule.arguments) {
    lines.push_back(commandLine(backend, arguments));
  }
  return list(lines);
}

// The names each build system reads a package's build file under, in the
// order it looks for them.
std::span<const std::string_view> buildFileNames(Backend backend) {
  return backend == Backend::Bazel
             ? std::span<const std::string_view>(kBazelBuildFiles)
             : std::span<const std::string_view>(kBuckBuildFiles);
}

// The build file of the package a file of a project belongs to, when
// that is not the project's root: the nearest directory above the file,
// below the root, that has a build file of its own. Both build systems
// let a package name only its own files by a path, so a file of such a
// package has to be named `//package:file`, and the package has to
// export it.
std::optional<fs::path> owningBuildFile(const Layout &layout, Backend backend,
                                        const std::string &file) {
  for (auto directory = fs::path(file).parent_path(); !directory.empty();
       directory = directory.parent_path()) {
    for (const auto name : buildFileNames(backend)) {
      if (fs::exists(layout.root / directory / name)) {
        return directory / name;
      }
    }
  }
  return std::nullopt;
}

// How a build file names a file of the project: by its path when the
// root package owns it, and by its package otherwise.
std::string projectLabel(const Layout &layout, Backend backend,
                         const std::string &file) {
  const auto owner = owningBuildFile(layout, backend, file);
  if (!owner) {
    return backend == Backend::Bazel ? absl::StrCat(":", file) : file;
  }
  const auto package = owner->parent_path().string();
  return absl::StrCat("//", package, ":", file.substr(package.size() + 1));
}

// How a build file names a file a rule wrote: the rule's output file to
// Bazel, `:rule/path`, and a sub-target of the rule to Buck2,
// `:rule[path]`. An artifact is named after its rule and then its path.
std::string outputLabel(Backend backend, std::string_view target,
                        std::string_view artifact) {
  if (backend == Backend::Bazel) {
    return absl::StrCat(":", artifact);
  }
  return absl::StrCat(":", target, "[", artifact.substr(target.size() + 1),
                      "]");
}

// Whether a file a rule reads is one every package of a shared workspace
// uses: the script, or a file of the guest's /bin and /etc.
bool isSharedFile(std::string_view file) {
  return file == kSandboxFile ||
         file.starts_with(absl::StrCat(kPlatformTarget, "/"));
}

// The attributes of a rule, which are the same in both build files but
// for how a file is named. A file of the workspace is `:path` to Bazel and
// `path` to Buck2. A file another rule wrote is that rule's output file
// to Bazel, `:rule/path`, and a sub-target of the rule to Buck2,
// `:rule[path]`. A rule's stamp is `:rule.ok` to Bazel and the rule
// itself to Buck2. Each build system is given each file, so that a rule
// runs again only when a file it reads has changed.
//
// A typed rule names the inputs its kind is about, and puts the rest in
// `data`: the manifest, the environment, the closure, the sandbox script,
// the guest's /bin and /etc, and the stamps of the rules whose
// directories the command uses.
std::vector<std::string> ruleAttributes(Backend backend, const Rule &rule,
                                        std::string_view macro,
                                        const Layout &layout) {
  const auto workspaceLabel = [&](const std::string &file) {
    // The script and the guest's files belong to the shared directory of
    // a shared workspace.
    if (layout.shared() && isSharedFile(file)) {
      return absl::StrCat("//", kSharedDirectory, ":", file);
    }
    return backend == Backend::Bazel ? absl::StrCat(":", file) : file;
  };
  const auto generatedLabel = [&](const Input &input) {
    return outputLabel(backend, input.target, input.artifact);
  };
  const auto stampLabel = [&](const std::string &target) {
    return backend == Backend::Bazel ? absl::StrCat(":", stampFile(target))
                                     : absl::StrCat(":", target);
  };

  // The files the command was given, as labels with the paths it sees
  // them at, and what the command needs besides.
  std::vector<std::pair<std::string, std::string>> given;
  Arguments data;
  for (const auto &file : rule.sources) {
    data.push_back(workspaceLabel(file));

    // A rule that is told where the closure's archives are has to be
    // given them.
    if (layout.shared() && file == kClosureFile) {
      data.push_back(absl::StrCat(":", kClosureTarget));
    }
  }
  // Buck2 hands a rule a file of another package under the file's name
  // in that package, and a command reads the file at its path in the
  // project. So a Buck2 rule is told that path for each such file.
  Arguments foreign;
  Arguments foreignPaths;
  for (const auto &input : rule.recorded) {
    const auto label = input.ofProject
                           ? projectLabel(layout, backend, input.artifact)
                           : workspaceLabel(input.artifact);
    if (input.ofProject && backend == Backend::Buck2 &&
        owningBuildFile(layout, backend, input.artifact)) {
      foreign.push_back(label);
      foreignPaths.push_back(input.artifact);
    }
    if (input.target == kPlatformTarget) {
      data.push_back(label);
    } else {
      given.emplace_back(label, input.path);
    }
  }
  std::ranges::sort(data);
  for (const auto &input : rule.generated) {
    given.emplace_back(generatedLabel(input), input.path);
  }
  Arguments stamps;
  for (const auto &target : rule.stamps) {
    stamps.push_back(stampLabel(target));
  }

  // The target that stands for the watched commands a gate takes in or
  // an archive waits for is named the same way in both build files.
  if (!rule.after.empty()) {
    stamps.push_back(absl::StrCat(":", rule.after));
  }

  // A command can see one file at several paths, when copies of the file
  // were raised. The file is one label however many paths it has, and
  // a label is listed once, so the first path stands for it.
  std::set<std::string> listed;
  std::erase_if(given, [&](const auto &input) {
    return !listed.insert(input.first).second;
  });

  // Takes out of `given` the inputs a predicate picks.
  const auto take = [&](const auto &picks) {
    Arguments taken;
    std::erase_if(given, [&](const auto &input) {
      if (!picks(input.second)) {
        return false;
      }
      taken.push_back(input.first);
      return true;
    });
    return taken;
  };
  const auto extensionIs = [](std::string_view extension) {
    return [extension](const std::string &path) {
      return fs::path(path).extension() == extension;
    };
  };
  const auto isLibrary = [](const std::string &path) {
    return fs::path(path).extension() == kArchiveLibraryExtension ||
           isSharedLibrary(path);
  };

  // Whatever is left of `given` once a kind has taken its inputs has no
  // attribute of its own and goes with the data, ahead of the stamps.
  const auto rest = [&] {
    Arguments all = data;
    for (const auto &input : given) {
      all.push_back(input.first);
    }
    all.insert(all.end(), stamps.begin(), stamps.end());
    return all;
  };

  // A rule that writes one file names the file, and one that writes
  // several lists them.
  const auto outputs = [&] {
    if (rule.outputs.size() == 1) {
      return attribute("out", quote(rule.outputs.front()));
    }
    return attribute("outs", list(rule.outputs));
  };

  std::vector<std::string> attributes{attribute("name", quote(rule.name))};
  if (macro == kWatchedRule) {
    attributes.push_back(attribute("srcs", list(stamps)));
    return attributes;
  }
  if (macro == kArchiveRule) {
    attributes.push_back(attribute("srcs", list(rest())));
    attributes.push_back(attribute(
        "out", quote(absl::StrCat(rule.name, kArchiveExtension))));
  } else if (macro == kCcObject) {
    const auto source = take([&](const std::string &path) {
      return rule.sourcePaths.contains(path);
    });
    attributes.push_back(attribute("src", quote(source.front())));

    // Every other file a compile reads is one it included.
    attributes.push_back(attribute("hdrs", list(take([](const auto &) {
      return true;
    }))));
    attributes.push_back(outputs());
    attributes.push_back(attribute("data", list(rest())));
  } else if (macro == kCcLibrary) {
    attributes.push_back(
        attribute("objs", list(take(extensionIs(kObjectExtension)))));
    attributes.push_back(outputs());
    attributes.push_back(attribute("data", list(rest())));
  } else if (macro == kCcBinary || macro == kCcSharedLibrary) {
    attributes.push_back(
        attribute("objs", list(take(extensionIs(kObjectExtension)))));
    attributes.push_back(attribute("deps", list(take(isLibrary))));
    attributes.push_back(outputs());
    attributes.push_back(attribute("data", list(rest())));
  } else if (macro == kRustLibrary || macro == kRustBinary ||
             macro == kRustProcMacro) {
    attributes.push_back(
        attribute("srcs", list(take(extensionIs(kRustSourceExtension)))));
    attributes.push_back(
        attribute("deps", list(take([&](const std::string &path) {
          const auto extension = fs::path(path).extension().string();
          return std::ranges::find(kRustCrateExtensions, extension) !=
                     std::end(kRustCrateExtensions) ||
                 isLibrary(path);
        }))));
    attributes.push_back(attribute("outs", list(rule.outputs)));
    attributes.push_back(attribute("data", list(rest())));
  } else {
    attributes.push_back(attribute("srcs", list(rest())));
    attributes.push_back(attribute("outs", list(rule.outputs)));
  }
  if (!foreign.empty()) {
    attributes.push_back(attribute("foreign", list(foreign)));
    attributes.push_back(attribute("foreign_paths", list(foreignPaths)));
  }
  attributes.push_back(attribute("cmd", commandLines(backend, rule, layout)));
  return attributes;
}

std::string renderRule(Backend backend, const Rule &rule,
                       const Layout &layout) {
  const auto macro = macroOf(rule);
  std::string text = absl::StrCat(macro, "(\n");
  for (const auto &line : ruleAttributes(backend, rule, macro, layout)) {
    absl::StrAppend(&text, kAttributeIndent, line, ",\n");
  }
  text += ")\n\n";

  // The file a typed rule wrote, under a name of its own.
  if (rule.fileName.empty()) {
    return text;
  }
  const auto fileRule = fileRuleOf(macro);
  absl::StrAppend(&text, fileRule, "(\n", kAttributeIndent,
                  attribute("name", quote(rule.fileName)), ",\n",
                  kAttributeIndent,
                  attribute("file", quote(outputLabel(backend, rule.name,
                                                      rule.outputs.front()))),
                  ",\n");

  // A program is told the shared libraries its link was given, and the
  // name the loader will ask for each by.
  if (fileRule == kProgramRule && !rule.libraries.empty()) {
    Arguments labels;
    Arguments names;
    for (const auto &library : rule.libraries) {
      const auto &file = library.file;
      labels.push_back(library.generated
                           ? outputLabel(backend, file.target, file.artifact)
                           : backend == Backend::Bazel
                                 ? absl::StrCat(":", file.artifact)
                                 : file.artifact);
      names.push_back(library.name);
    }
    absl::StrAppend(&text, kAttributeIndent, attribute("libs", list(labels)),
                    ",\n", kAttributeIndent,
                    attribute("lib_names", list(names)), ",\n");
  }

  // The watched commands recorded before the command that wrote the
  // file, which whoever builds or runs the file waits for.
  if (!rule.fileAfter.empty()) {
    absl::StrAppend(
        &text, kAttributeIndent,
        attribute("after", list({absl::StrCat(":", rule.fileAfter)})), ",\n");
  }
  return text + ")\n\n";
}

// Gives every rule the shared libraries of its libraries. A library that
// needs another one says so by name, and the loader looks for that name
// when the program starts. The program's own link may never have opened
// the file. The link that made a library was given what the library
// needs, so the libraries are followed from one link to the next. Under
// a name a rule already has a library for, the rule keeps that library.
void closeLibraries(std::vector<Rule> &rules) {
  // What each rule's own command was given, by rule.
  std::map<std::string, std::vector<Library>> given;
  for (const auto &rule : rules) {
    given[rule.name] = rule.libraries;
  }

  for (auto &rule : rules) {
    std::set<std::string> names;
    for (const auto &library : rule.libraries) {
      names.insert(library.name);
    }

    // The list grows while it is walked: a library added here is looked
    // at in turn.
    for (size_t index = 0; index < rule.libraries.size(); ++index) {
      const auto library = rule.libraries[index];
      if (!library.generated) {
        continue;
      }
      for (const auto &needed : given[library.file.target]) {
        if (names.insert(needed.name).second) {
          rule.libraries.push_back(needed);
        }
      }
    }
  }
}

// Makes what somebody builds wait for the watched commands recorded
// before the command that made it. A watched command reads a source, runs
// again after an edit, and fails when it ends another way than it did or
// leaves something else. The builder may have decided what to run next
// by how any such command ended, as a shell does with a command it
// tests, whether or not something reads what the command wrote. An
// archive waits for all of them, and a file with a name of its own for
// those recorded before the command that wrote it.
//
// The commands are collected by gates. A gate holds the commands since
// the gate before it and takes that gate in, so a target names one gate
// and each command is listed once. The commands themselves wait for
// nothing more than their inputs: they run side by side, and one object
// can be built while another source does not compile.
void addGates(std::vector<Rule> &rules,
              const std::map<uint64_t, std::string> &watchedAt) {
  if (watchedAt.empty()) {
    return;
  }
  const auto gateName = [](uint64_t step) {
    return absl::StrCat(kWatchedPrefix, step);
  };

  // Where a gate is needed: at the last watched command before each
  // named file's command, and at the last one of all for an archive.
  std::set<uint64_t> cuts;
  for (auto &rule : rules) {
    if (rule.archive) {
      const auto last = watchedAt.rbegin()->first;
      cuts.insert(last);
      rule.after = gateName(last);
      continue;
    }
    const auto later = watchedAt.lower_bound(rule.step);
    if (rule.fileName.empty() || later == watchedAt.begin()) {
      continue;
    }
    const auto last = std::prev(later)->first;
    cuts.insert(last);
    rule.fileAfter = gateName(last);
  }

  // Each gate, by the rule of the last command it holds.
  std::map<std::string, Rule> gateOf;
  std::string previous;
  auto member = watchedAt.begin();
  for (const auto cut : cuts) {
    Rule gate;
    gate.name = gateName(cut);
    gate.gate = true;
    gate.after = previous;
    for (; member != watchedAt.end() && member->first <= cut; ++member) {
      gate.stamps.insert(member->second);
    }
    previous = gate.name;
    gateOf.emplace(watchedAt.at(cut), std::move(gate));
  }

  // A gate is written after the rule of its last command.
  std::vector<Rule> all;
  for (auto &rule : rules) {
    const auto own = gateOf.find(rule.name);
    all.push_back(std::move(rule));
    if (own != gateOf.end()) {
      all.push_back(std::move(own->second));
    }
  }
  rules = std::move(all);
}

// Gives the file each typed rule writes a name of its own: the file's
// place in the build tree. A rule is named after the step it was recorded
// at, and steps move from one recording to the next. A name that comes
// from a path stays put, so a rule written by hand can depend on
// `:greet` or `:src/hello.o` and still build after the project is
// converted again.
//
// The directory every such file is under, as `hello-2.12.3/` is in a
// build from a tarball, is left off. Two rules that write one path wrote
// two versions of the file, and the name goes to the later one. A name
// that a rule or a file of the workspace already has is not given out,
// and neither is one that reads like a gate's.
void nameFiles(std::vector<Rule> &rules, const fs::path &workspace) {
  // The rules that have a file to name, with the file's place below the
  // build tree.
  std::vector<std::pair<Rule *, std::string>> candidates;
  for (auto &rule : rules) {
    const auto macro = macroOf(rule);
    const bool typed = macro != kRecordedRule && macro != kArchiveRule &&
                       macro != kWatchedRule;
    if (!typed || rule.writes.empty() || !rule.writes.starts_with(kBuildTree)) {
      continue;
    }
    candidates.emplace_back(&rule, rule.writes.substr(kBuildTree.size()));
  }
  if (candidates.empty()) {
    return;
  }

  // Leave off the first directory when all the files share one.
  const auto top = [](const std::string &place) {
    return place.substr(0, place.find('/') + 1);
  };
  const auto shared = top(candidates.front().second);
  const bool common =
      !shared.empty() &&
      std::ranges::all_of(candidates, [&](const auto &candidate) {
        return top(candidate.second) == shared;
      });

  // The later rule takes a name two rules would have.
  static const std::regex allowed{std::string(kTargetName)};
  std::set<std::string> taken;
  for (const auto &rule : rules) {
    taken.insert(rule.name);
  }
  std::map<std::string, Rule *> named;
  for (const auto &[rule, place] : candidates) {
    const auto name = common ? place.substr(shared.size()) : place;
    if (!std::regex_match(name, allowed) || taken.contains(name) ||
        name.starts_with(kWatchedPrefix) || fs::exists(workspace / name)) {
      continue;
    }
    named[name] = rule;
  }
  for (const auto &[name, rule] : named) {
    rule->fileName = name;
  }
}

// A build file: the rules it uses, loaded from the file of definitions
// the workspace ships, then one call per operation.
std::string buildFile(Backend backend, const std::vector<Rule> &rules,
                      const Layout &layout, std::string_view preamble = "") {
  std::set<std::string> macros;
  for (const auto &rule : rules) {
    macros.insert(std::string(macroOf(rule)));
    if (!rule.fileName.empty()) {
      macros.insert(std::string(fileRuleOf(macroOf(rule))));
    }
  }
  // Bazel loads a file of its own package by path. Buck2 takes a path
  // only as a package and a file, so a project's rules are loaded from
  // the support directory as from a package.
  std::string definitions;
  if (layout.shared()) {
    definitions = absl::StrCat("//", kSharedDirectory, ":", kBazelRulesFile);
  } else if (backend == Backend::Bazel) {
    definitions = absl::StrCat(":", layout.prefix(), kBazelRulesFile);
  } else if (layout.project) {
    definitions = absl::StrCat("//", kSupportDirectory, ":", kBuckRulesFile);
  } else {
    definitions = absl::StrCat(":", kBuckRulesFile);
  }
  Arguments loaded{quote(definitions)};
  for (const auto &macro : macros) {
    loaded.push_back(quote(macro));
  }

  // A recorded build's rules are the build file.
  const auto load = absl::StrCat("load(", absl::StrJoin(loaded, ", "),
                                 ")\n\n", preamble);
  std::string body;
  for (const auto &rule : rules) {
    body += renderRule(backend, rule, layout);
  }
  if (!layout.project) {
    return load + body;
  }

  // A project's rules are the body of a function, so that the build file
  // that calls the function can be anybody's. A file written into a
  // project says who wrote it.
  std::string text = absl::StrCat(kGeneratedLine, load, "def ",
                                  kTargetsFunction, "():\n");
  for (const std::string_view line : absl::StrSplit(body, '\n')) {
    absl::StrAppend(&text, line.empty() ? "" : kAttributeIndent, line, "\n");
  }
  return text;
}

// Says what the packages below a project's root have to export for the
// converted rules to read their files. Those build files are the
// project's, so genrulify writes about them and not into them. A file
// whose name a build file already has in quotes is taken as dealt with.
void noteExports(const std::vector<Rule> &rules, const Layout &layout) {
  for (const auto backend : {Backend::Bazel, Backend::Buck2}) {
    // The files to export, by the build file of their package.
    std::map<fs::path, std::set<std::string>> wanted;
    for (const auto &rule : rules) {
      for (const auto &input : rule.recorded) {
        if (!input.ofProject) {
          continue;
        }
        const auto owner = owningBuildFile(layout, backend, input.artifact);
        if (!owner) {
          continue;
        }
        const auto package = owner->parent_path().string();
        const auto name = input.artifact.substr(package.size() + 1);
        const auto text = readBytes(layout.root / *owner);
        if (text.find(quote(name)) == std::string::npos) {
          wanted[*owner].insert(name);
        }
      }
    }
    for (const auto &[buildFile, names] : wanted) {
      llvm::errs() << (layout.root / buildFile).string()
                   << " has to export the files of its package that the "
                      "converted rules read. Add:\n";
      if (backend == Backend::Bazel) {
        Arguments quoted;
        for (const auto &name : names) {
          quoted.push_back(quote(name));
        }
        llvm::errs() << "  exports_files([" << absl::StrJoin(quoted, ", ")
                     << "])\n";
        continue;
      }
      for (const auto &name : names) {
        llvm::errs() << "  export_file(name = " << quote(name)
                     << ", visibility = [\"PUBLIC\"])\n";
      }
    }
  }
}

// Whether a file of a project is one genrulify wrote, or is not there.
bool replaceable(const fs::path &file) {
  if (!fs::exists(file)) {
    return true;
  }
  return readBytes(file).starts_with(kGeneratedMark);
}

// The label a build file loads a project's rules from.
std::string targetsLabel(Backend backend) {
  if (backend == Backend::Bazel) {
    return absl::StrCat(":", kSupportDirectory, "/", kBazelTargetsFile);
  }
  return absl::StrCat("//", kSupportDirectory, ":", kBuckTargetsFile);
}

// The two lines by which a build file makes a project's rules.
std::string loadLine(Backend backend) {
  return absl::StrCat("load(", quote(targetsLabel(backend)), ", ",
                      quote(kTargetsFunction), ")");
}
std::string callLine() { return absl::StrCat(kTargetsFunction, "()"); }

// Gives a project a build file that makes its rules, unless the project
// has one somebody else wrote. That file is left as it is, and when it
// does not load the rules the two lines that would are printed.
//
// A build system reads a package's build file under more than one name
// and takes the first it finds. A loader written beside a file of the
// project's under the other name would hide that file, or be hidden by
// it, so every name is looked at, and a loader genrulify wrote earlier
// goes once the project has a file of its own.
void writeLoader(Backend backend, const fs::path &project) {
  const auto names = buildFileNames(backend);

  // The project's own build file is the first one the build system would
  // read that genrulify did not write.
  std::optional<fs::path> own;
  for (const auto name : names) {
    if (fs::exists(project / name) && !replaceable(project / name)) {
      own = project / name;
      break;
    }
  }
  if (!own) {
    writeBytes(project / (backend == Backend::Bazel ? kBazelBuildFile
                                                    : kBuckBuildFile),
               absl::StrCat(kGeneratedLine, loadLine(backend), "\n\n",
                            callLine(), "\n"));
    return;
  }
  for (const auto name : names) {
    if (fs::exists(project / name) && replaceable(project / name)) {
      fs::remove(project / name);
    }
  }
  if (readBytes(*own).find(loadLine(backend)) != std::string::npos) {
    return;
  }
  llvm::errs() << own->string()
               << " is not genrulify's and was left as it is. To build the "
                  "converted targets from it, add:\n  "
               << loadLine(backend) << "\n  " << callLine() << "\n";
}

// The process groups a recording's report lists without a replay, or none
// when the recording has not been checked.
std::set<uint64_t> groupsNotReplayed(const Recording &recording) {
  std::set<uint64_t> steps;
  const auto report = recording.directory / kReportFile;
  if (!fs::exists(report)) {
    return steps;
  }
  static const std::set<std::string> replayed{
      std::string(rungName(Rung::Narrow)), std::string(rungName(Rung::Near)),
      std::string(rungName(Rung::Traced)), std::string(rungName(Rung::Wide))};
  for (const auto &group : Json::parse(readBytes(report)).at("groups")) {
    if (!replayed.contains(group.at("outcome").get<std::string>())) {
      steps.insert(group.at("step").get<uint64_t>());
    }
  }
  return steps;
}

// Copies a recorded file's bytes into the workspace under an artifact name.
void writeArtifact(const Recording &recording, const Entry &entry,
                   const fs::path &file) {
  fs::create_directories(file.parent_path());
  fs::copy_file(recording.blob(entry.content), file,
                fs::copy_options::overwrite_existing);
}

// Where a file of the shared directory is written until all of it is
// there. Several packages can be emitted into one workspace at once, and
// each writes the shared files, so every writer has a name of its own.
fs::path partialName(const fs::path &file) {
  return absl::StrCat(file.string(), ".", getpid(), ".partial");
}

// Puts a file every package uses into the shared directory. A file that
// is there with the same bytes is left alone, so that a rule which read
// the file does not run again. One with other bytes is replaced: the
// file is the script or the rule definitions of an older compiler.
void installShared(const fs::path &file, std::string_view bytes,
                   fs::perms permissions) {
  if (fs::exists(file) && readBytes(file) == bytes) {
    return;
  }
  fs::create_directories(file.parent_path());
  const auto partial = partialName(file);
  writeBytes(partial, std::string(bytes));
  fs::permissions(partial, permissions);
  fs::rename(partial, file);
}

// The same for a file of the guest's /bin and /etc. Every package's
// rules read the one copy, so a build recorded with another guest cannot
// join the workspace.
void installPlatformFile(const Recording &recording, const Entry &entry,
                         const fs::path &file) {
  if (fs::exists(file)) {
    check(digest(file) == entry.content,
          absl::StrCat(entry.path, " of the recorded guest is not the ",
                       file.string(),
                       " that the workspace's other packages were recorded "
                       "with"));
    return;
  }
  fs::create_directories(file.parent_path());
  const auto partial = partialName(file);
  fs::copy_file(recording.blob(entry.content), partial,
                fs::copy_options::overwrite_existing);
  fs::rename(partial, file);
}

// The last name of a store path.
std::string storeName(const std::string &path) {
  return fs::path(path).filename().string();
}

// The name of a recorded build's package in a shared workspace: the last
// name of the store path of its `out`, or of its first output when it
// has no output of that name.
std::string packageName(const Recording &recording) {
  check(!recording.outputs.empty(), "the recording has no output");
  const auto out = recording.outputs.find(std::string(kDefaultOutput));
  return storeName(out != recording.outputs.end()
                       ? out->second
                       : recording.outputs.begin()->second);
}

// What closure.txt holds in a shared workspace: each store path, and the
// package of the workspace that has the path's archive.
std::string linkedClosure(const Recording &recording) {
  std::string text;
  for (const auto &path : recording.closure) {
    absl::StrAppend(&text, path, std::string(1, kFieldSeparator),
                    kStoreDirectory, "/", storeName(path), "\n");
  }
  return text;
}

// A filegroup with one label on each line.
std::string filegroup(std::string_view name, const Arguments &labels) {
  return absl::StrCat("filegroup(\n", kAttributeIndent,
                      attribute("name", quote(name)), ",\n", kAttributeIndent,
                      attribute("srcs", list(labels)), ",\n)\n\n");
}

// One output of a recorded build: its name, its store path, the digest
// its archive must have and the target that builds the archive.
struct BuiltOutput {
  std::string name;
  std::string path;
  std::string digest;
  std::string target;
};

// What a package of a shared workspace says before its rules: that any
// package may read it, the store paths of its closure as one target, and
// the archives of its outputs as another.
std::string packagePreamble(const Recording &recording,
                            const std::vector<BuiltOutput> &outputs) {
  Arguments closure;
  for (const auto &path : recording.closure) {
    closure.push_back(absl::StrCat("//", kStoreDirectory, "/", storeName(path),
                                   ":", kStorePathTarget));
  }
  Arguments archives;
  for (const auto &output : outputs) {
    archives.push_back(absl::StrCat(":", output.target));
  }
  return absl::StrCat(kPublicPackage, filegroup(kClosureTarget, closure),
                      filegroup(kOutputsTarget, archives));
}

// What a package says of itself for `link`: the store path and the
// archive digest of each output, the target that builds the archive, and
// the store paths the build read.
std::string packageDescription(const Recording &recording,
                               const Layout &layout,
                               const std::vector<BuiltOutput> &outputs) {
  Json built = Json::object();
  for (const auto &output : outputs) {
    built[output.name] = {{"path", output.path},
                          {"digest", output.digest},
                          {"target", output.target}};
  }
  return Json{{"name", recording.name},
              {"package", layout.package},
              {"outputs", built},
              {"closure", recording.closure}}
             .dump(kJsonIndent) +
         "\n";
}


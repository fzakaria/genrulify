// Where a workspace keeps what genrulify wrote. A recorded build is a
// workspace of its own and keeps everything at its root. A project keeps
// its own files at the root.
struct Layout {
  bool project = false;

  // The directory of a project converted in place, or the directory of a
  // package of a shared workspace.
  fs::path root;

  // The package of a shared workspace the rules are written into, as
  // Bazel names it, `pkgs/NAME`. Empty for a workspace of one build.
  std::string package;

  bool shared() const { return !package.empty(); }

  // What comes before the name of a file genrulify wrote: nothing, or the
  // support directory and a slash.
  std::string prefix() const {
    return project ? absl::StrCat(kSupportDirectory, "/") : "";
  }
};


void checkProjectDirectory(const fs::path &project) {
  check(fs::is_directory(project), project.string() + " is not a directory");

  // The support directory is replaced, and so is what an interrupted
  // conversion left behind. A directory of either name without the mark
  // genrulify leaves in its own is the project's.
  for (const auto name :
       {kSupportDirectory, kStagingDirectory, kPreviousDirectory}) {
    const auto directory = project / name;
    const auto mark = directory / kOwnershipFile;
    check(!fs::exists(directory) || (fs::exists(mark) && replaceable(mark)),
          absl::StrCat(directory.string(),
                       " was not written by genrulify: move it away, or "
                       "convert a copy of the project"));
  }
}

void emitWorkspace(mlir::ModuleOp module, const Recording &recording,
                   const fs::path &destination) {
  emitLayout(module, recording,
             Layout{!recording.source.empty(), destination, ""});
}

std::string emitPackage(mlir::ModuleOp module, const Recording &recording,
                        const fs::path &workspace) {
  check(recording.source.empty(),
        "a project converted in place builds its own sources and cannot be "
        "a package of a shared workspace");
  const auto name = packageName(recording);
  const Layout layout{false, workspace / kPackagesDirectory / name,
                      absl::StrCat(kPackagesDirectory, "/", name)};
  emitLayout(module, recording, layout);

  // The label of the archive of the package's main output.
  size_t outputCount = 0;
  for (auto &op : module.getBody()->getOperations()) {
    outputCount += llvm::isa<OutputOp>(op) ? 1 : 0;
  }
  for (auto &op : module.getBody()->getOperations()) {
    auto output = llvm::dyn_cast<OutputOp>(op);
    if (output && storeName(output.getPath().str()) == name) {
      return absl::StrCat("//", layout.package, ":",
                          targetName(&op, outputCount));
    }
  }
  throw std::runtime_error("the graph has no output for " + name);
}

namespace {
void emitLayout(mlir::ModuleOp module, const Recording &recording,
                const Layout &layout) {
  // A recorded build gets a new directory. A project is converted where it
  // is, so its directory exists, and only what genrulify wrote there
  // before is replaced.
  //
  // A project's support directory is written under another name and put
  // in place once every file is there, so that a conversion that fails
  // leaves the last one as it was. A package of a shared workspace is
  // written the same way, beside the place it will have.
  const auto &destination = layout.root;
  const auto support =
      layout.project
          ? destination / kStagingDirectory
          : layout.shared()
                ? destination.parent_path() /
                      absl::StrCat(".", destination.filename().string(),
                                   ".staging")
                : destination;

  // The directory of a shared workspace that every package reads.
  const auto shared =
      destination.parent_path().parent_path() / kSharedDirectory;
  if (layout.project) {
    checkProjectDirectory(destination);
    removeTree(support);
    fs::create_directory(support);
  } else if (layout.shared()) {
    fs::create_directories(support.parent_path());
    removeTree(support);
    fs::create_directory(support);
  } else {
    check(fs::create_directory(destination), "destination already exists");
  }
  try {
    if (layout.project) {
      writeBytes(support / kOwnershipFile, std::string(kGeneratedLine));

      // The files of rules are there from the start, so that a source of
      // the project with either name is noticed like any other clash.
      writeBytes(support / kBazelTargetsFile, "");
      writeBytes(support / kBuckTargetsFile, "");
    }
    writeSharedFiles(recording, support);

    // A package of a shared workspace reads the script from the shared
    // directory, and is told where the workspace has the archive of each
    // store path.
    const auto executable = fs::perms::owner_all | fs::perms::group_read |
                            fs::perms::group_exec | fs::perms::others_read |
                            fs::perms::others_exec;
    const auto readable = fs::perms::owner_read | fs::perms::owner_write |
                          fs::perms::group_read | fs::perms::others_read;
    if (layout.shared()) {
      const auto script = readBytes(support / kSandboxFile);
      fs::remove(support / kSandboxFile);
      writeBytes(support / kClosureFile, linkedClosure(recording));
      installShared(shared / kSandboxFile, script, executable);
      installShared(shared / kBazelRulesFile, kBazelRules, readable);
      installShared(shared / kBazelBuildFile, kSharedBuildFile, readable);
    }

    // The guest's /bin and /etc, as files every replay rule reads.
    const ArtifactOf platformArtifact = [](const Entry &entry) {
      return artifactName(kPlatformTarget, entry.path);
    };
    std::set<Input> platformFiles;
    for (const auto &[path, entry] : recording.platform()) {
      if (entry.kind == EntryKind::File) {
        const auto artifact = platformArtifact(entry);
        if (layout.shared()) {
          installPlatformFile(recording, entry, shared / artifact);
        } else {
          writeArtifact(recording, entry, support / artifact);
        }
        platformFiles.insert(
            {std::string(kPlatformTarget), layout.prefix() + artifact, path,
             false});
      }
    }

    size_t outputCount = 0;
    for (auto &op : module.getBody()->getOperations()) {
      outputCount += llvm::isa<OutputOp>(op) ? 1 : 0;
    }

    // A rule is only as good as the replay that checked its group. When
    // the recording has a report, a group the report says was not replayed
    // must not become a rule: the report was made with other passes, which
    // removed the group before the checker saw it.
    const auto unchecked = groupsNotReplayed(recording);

    // Whether a value is a file of the project's source tree: a result of
    // the literal that holds the tree.
    const auto isSource = [&](mlir::Value value) {
      auto literal = llvm::dyn_cast<LiteralOp>(value.getDefiningOp());
      return layout.project && literal && literal.getName().str() == kSourceName;
    };

    // A file is read under the name of the version that first had its
    // bytes. A copy has no file of its own: whoever reads the copy lists
    // the original and stages it at the copy's path. A file of a project's
    // source tree is the project's own file, named by where it is in the
    // project.
    const auto artifactOf = [&](mlir::Value value) {
      const auto original = contentSource(value);
      const auto path = entryOf(original)->path;
      if (isSource(original)) {
        check(path.size() > recording.source.size(),
              "a source that is one file cannot be converted in place");
        const auto relative = path.substr(recording.source.size() + 1);

        // The sandbox script looks for a file by name in the support
        // directory before the project, so a source file with the name of
        // a support file would be read as the support file.
        check(!fs::exists(support / relative),
              absl::StrCat("the project's ", relative,
                           " has the name of a file genrulify keeps under ",
                           kSupportDirectory,
                           "/, and a rule could not tell the two apart: "
                           "rename the file"));
        return relative;
      }
      return artifactName(targetName(original.getDefiningOp(), outputCount),
                          path);
    };

    // The commands of a project that depend on its sources. Their rules
    // take what the command leaves, and say what that was in their stamp.
    const auto dependent = layout.project
                               ? dependsOnSource(module)
                               : std::set<mlir::Operation *>{};

    // Where the mode or the symlink target of an operand is read from
    // when a step is given it: the stamp of the source-reading command
    // that made the entry, or the project's own file. Every other entry
    // is as the recording has it.
    const auto originOf = [&](mlir::Value value) -> std::string {
      auto *producer = value.getDefiningOp();
      if (llvm::isa<ExecOp>(producer) && dependent.contains(producer)) {
        return targetName(producer, outputCount);
      }
      if (entryOf(value)->kind == EntryKind::File &&
          isSource(contentSource(value))) {
        return std::string(kCheckoutOrigin);
      }
      return "";
    };

    // Sorts a rule's operands into workspace files and other rules' files.
    const auto addOperands = [&](Rule &rule, mlir::OperandRange operands) {
      for (const auto value : operands) {
        const auto original = contentSource(value);
        auto *producer = original.getDefiningOp();
        const auto target = targetName(producer, outputCount);
        const bool file = entryOf(value)->kind == EntryKind::File;
        const auto path = entryOf(value)->path;
        if (llvm::isa<LiteralOp>(producer)) {
          if (!file) {
            continue;
          }

          // The project has its own files where they are. Recorded bytes
          // are with the rest of what genrulify wrote.
          const auto artifact = artifactOf(value);
          rule.recorded.insert(
              {target,
               isSource(original) ? artifact : layout.prefix() + artifact,
               path, isSource(original)});
          continue;
        }
        rule.stamps.insert(target);
        if (file) {
          rule.generated.insert({target, artifactOf(value), path});
        }
      }
    };

    // The watched commands, by the step each was recorded at.
    std::map<uint64_t, std::string> watchedAt;
    std::vector<Rule> rules;
    std::vector<BuiltOutput> builtOutputs;
    for (auto &op : module.getBody()->getOperations()) {
      if (auto literal = llvm::dyn_cast<LiteralOp>(op)) {
        // A project's source tree is already in the workspace.
        if (layout.project && literal.getName().str() == kSourceName) {
          continue;
        }

        // Recorded bytes are files checked into the workspace.
        const auto target = targetName(&op, outputCount);
        for (const auto attribute :
             literal.getWrites().getAsRange<EntryAttr>()) {
          const auto entry = fromAttribute(attribute);
          if (entry.kind == EntryKind::File) {
            writeArtifact(recording, entry,
                          support / artifactName(target, entry.path));
          }
        }
        continue;
      }

      // A copy needs no rule.
      if (llvm::isa<CopyOp>(op)) {
        continue;
      }

      Rule rule;
      Action action;
      if (auto exec = llvm::dyn_cast<ExecOp>(op)) {
        check(!unchecked.contains(exec.getStep()),
              absl::StrCat("the group at step ", exec.getStep(),
                           " was not replayed by `check`: check the recording "
                           "with the passes the graph was optimized with"));
        action = execAction(exec, recording, artifactOf, platformArtifact,
                            originOf);
        action.trusted = dependent.contains(&op);
        if (action.trusted) {
          action.removed = removedPaths(recording, exec.getStep());
        }
        rule.step = exec.getStep();
        if (exec.getWatched()) {
          watchedAt[rule.step] = action.name;
        }
        rule.recorded.insert(platformFiles.begin(), platformFiles.end());

        // A group raised to a kind of rule is one command, and a compile
        // says which of its inputs is the source.
        if (const auto kind = exec.getRule()) {
          rule.kind = kind->str();
          for (const auto &process : action.processes) {
            const auto paths = sourcePaths(process);
            rule.sourcePaths.insert(paths.begin(), paths.end());
          }
        }
        addOperands(rule, exec.getInputs());

        // The shared libraries among the files the command was given,
        // under each name the command could have known one by: the
        // file's own, and that of a symlink to the file.
        std::map<std::string, Library> files;
        for (const auto &input : rule.generated) {
          files[input.path] = {"", input, true};
        }
        for (const auto &input : rule.recorded) {
          if (input.target != kPlatformTarget) {
            files.emplace(input.path, Library{"", input, false});
          }
        }
        for (const auto &given : action.inputs) {
          const auto &entry = given.entry;
          if (!isSharedLibrary(entry.path) ||
              entry.kind == EntryKind::Directory) {
            continue;
          }
          const fs::path path(entry.path);
          const auto held =
              entry.kind == EntryKind::Symlink
                  ? (path.parent_path() / entry.content).lexically_normal()
                  : path;
          if (const auto file = files.find(held.string());
              file != files.end()) {
            auto library = file->second;
            library.name = path.filename().string();
            rule.libraries.push_back(std::move(library));
          }
        }
        for (const auto &result : action.results) {
          if (!result.artifact.empty()) {
            rule.outputs.push_back(result.artifact);
            rule.writes = result.entry.path;
          }
        }
        if (rule.outputs.size() != 1) {
          rule.writes.clear();
        }
      } else if (auto output = llvm::dyn_cast<OutputOp>(op)) {
        action = outputAction(output, outputCount, artifactOf, originOf);
        rule.archive = true;

        // A recorded build has one right answer for each output, which is
        // the output as the recording saw it. The archive rule is given
        // that digest and fails on any other archive, so one target says
        // whether every rule, literal and copy below it came out right.
        if (!layout.project) {
          Scratch scratch;
          const auto reference = scratch.path / kReferenceArchive;
          writeReference(recording, output.getName().str(), reference);
          action.archiveDigest = digest(reference);
        }
        builtOutputs.push_back({output.getName().str(), output.getPath().str(),
                                action.archiveDigest, action.name});
        addOperands(rule, output.getEntries());
      } else {
        throw std::runtime_error("unsupported operation: " +
                                 op.getName().getStringRef().str());
      }
      rule.name = action.name;
      for (const auto &file : sharedFiles(action, recording)) {
        rule.sources.insert(layout.prefix() + file);
      }
      for (const auto &file : writeActionFiles(action, support)) {
        rule.sources.insert(layout.prefix() + file);
      }
      rule.arguments = actionArguments(action, recording);
      rules.push_back(std::move(rule));
    }

    closeLibraries(rules);
    nameFiles(rules, layout.shared() ? support : destination);
    addGates(rules, watchedAt);

    // A package of a shared workspace is one build file for Bazel and
    // what the package says of itself. A file must not take the name of
    // one of the package's own targets.
    if (layout.shared()) {
      for (auto &rule : rules) {
        if (rule.fileName == kClosureTarget ||
            rule.fileName == kOutputsTarget) {
          rule.fileName.clear();
        }
      }
      writeBytes(support / kBazelBuildFile,
                 buildFile(Backend::Bazel, rules, layout,
                           packagePreamble(recording, builtOutputs)));
      writeBytes(support / kPackageFile,
                 packageDescription(recording, layout, builtOutputs));
      removeTree(destination);
      fs::rename(support, destination);
      return;
    }
    const auto bazelFile = buildFile(Backend::Bazel, rules, layout);
    const auto buckFile = buildFile(Backend::Buck2, rules, layout);
    writeBytes(support / kBazelRulesFile, kBazelRules);
    writeBytes(support / kBuckRulesFile, kBuckRules);

    // A recorded build's directory is new, so its build files are
    // written where they belong. A project's rules are files of the
    // support directory, and the conversion is put in place by renames
    // alone: the last support directory moves aside, the new one moves
    // in, and the last one is removed. The project's build files only
    // load the rules, and say the same after every conversion.
    if (!layout.project) {
      writeBytes(destination / kBazelBuildFile, bazelFile);
      writeBytes(destination / kBuckBuildFile, buckFile);
    } else {
      writeBytes(support / kBazelTargetsFile, bazelFile);
      writeBytes(support / kBuckTargetsFile, buckFile);
      const auto final = destination / kSupportDirectory;
      const auto previous = destination / kPreviousDirectory;
      removeTree(previous);
      if (fs::exists(final)) {
        fs::rename(final, previous);
      }
      fs::rename(support, final);
      removeTree(previous);
      writeLoader(Backend::Bazel, destination);
      writeLoader(Backend::Buck2, destination);
      noteExports(rules, layout);
    }

    // What makes the directory a workspace. A project that already is one
    // keeps its own.
    const std::string mark(layout.project ? kGeneratedLine : "");
    const auto toolchains =
        destination / kBuckToolchainsDirectory / kBuckBuildFile;
    const std::pair<fs::path, std::string> settings[] = {
        {destination / kBazelWorkspaceFile, mark},
        {destination / kBazelModuleFile, mark},
        {destination / kBuckConfigFile, absl::StrCat(mark, kBuckConfig)},
        {toolchains, absl::StrCat(mark, kBuckToolchains)}};
    for (const auto &[file, text] : settings) {
      if (layout.project && !replaceable(file)) {
        continue;
      }
      fs::create_directories(file.parent_path());
      writeBytes(file, text);
    }
  } catch (...) {
    // Never the project itself, and never a package that was there
    // before: only what this call was writing.
    removeTree(layout.project || layout.shared() ? support : destination);
    throw;
  }
}
} // namespace

void writeReference(const Recording &recording, const std::string &output,
                    const fs::path &archive) {
  const auto path = recording.outputs.find(output);
  check(path != recording.outputs.end(),
        "the derivation has no output " + output);

  // Pack the entries below the output path as the builder left them, with
  // each file's bytes read straight from the recording's blobs.
  Action action;
  action.name = output;
  action.output = path->second;
  for (const auto &[entryPath, entry] : recording.state(recording.finalStep)) {
    if (isBelow(entryPath, path->second)) {
      action.inputs.push_back(
          {entry, entry.kind == EntryKind::File
                      ? absl::StrCat(kBlobsDirectory, "/", entry.content)
                      : ""});
    }
  }

  Scratch scratch;
  writeSharedFiles(recording, scratch.path);
  writeActionFiles(action, scratch.path);
  execute(sandboxCommand(action, recording, scratch.path, scratch.path));
  fs::copy_file(outputDirectory(scratch.path) /
                    absl::StrCat(output, kArchiveExtension),
                archive, fs::copy_options::overwrite_existing);
}

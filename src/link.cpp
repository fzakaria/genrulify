std::string nixBase32(std::string_view hex) {
  const auto bytes = fromHex(hex);
  const size_t length =
      (bytes.size() * kBitsPerByte + kBitsPerDigit - 1) / kBitsPerDigit;
  std::string text;
  for (size_t index = length; index-- > 0;) {
    const size_t bit = index * kBitsPerDigit;
    const size_t byte = bit / kBitsPerByte;
    const unsigned shift = bit % kBitsPerByte;
    unsigned digit = static_cast<uint8_t>(bytes[byte]) >> shift;
    if (byte + 1 < bytes.size()) {
      digit |= static_cast<unsigned>(static_cast<uint8_t>(bytes[byte + 1]))
               << (kBitsPerByte - shift);
    }
    text.push_back(kBase32Digits[digit & kDigitMask]);
  }
  return text;
}

void linkWorkspace(const fs::path &workspace, const std::string &cache,
                   const fs::path &attributes) {
  // What each package builds and what each read.
  std::map<std::string, Built> builtBy;
  std::set<std::string> wanted;
  std::set<std::string> packages;
  const auto packagesDirectory = workspace / kPackagesDirectory;
  check(fs::is_directory(packagesDirectory),
        absl::StrCat(workspace.string(), " has no ", kPackagesDirectory,
                     "/: emit a build into the workspace first"));
  for (const auto &entry : fs::directory_iterator(packagesDirectory)) {
    const auto description = entry.path() / kPackageFile;
    if (!fs::exists(description)) {
      continue;
    }
    const auto package = Json::parse(readBytes(description));
    packages.insert(entry.path().filename().string());
    for (const auto &[name, output] : package.at("outputs").items()) {
      const std::string path = output.at("path");
      builtBy[path] = {package.at("package"), output.at("target"),
                       output.at("digest")};
      wanted.insert(path);
    }
    for (const std::string path : package.at("closure")) {
      wanted.insert(path);
    }
  }

  // What the cache has of them.
  const auto narinfos = workspace / kNarinfoDirectory;
  fetchNarinfos(narinfos, cache, wanted);

  // Give each store path a package. A path a package builds is that
  // package's archive when the cache has the same archive, or has none:
  // then whatever read the path read those bytes, or nothing else could
  // have made them. When the cache has another archive, the builds that
  // read the path read the cache's, and the workspace fetches it.
  const auto storeDirectory = workspace / kStoreDirectory;
  std::map<Origin, size_t> origins;
  size_t differing = 0;
  std::map<std::string, Narinfo> fetched;
  Arguments missing;
  for (const auto &path : wanted) {
    const auto name = storeName(path);
    const auto directory = storeDirectory / name;
    const auto narinfo = readNarinfo(narinfos, path);
    const auto built = builtBy.find(path);
    const bool same = built != builtBy.end() &&
                      (!narinfo || narinfo->archiveDigest == built->second.digest);
    if (built != builtBy.end() && !same) {
      ++differing;
    }

    // The package's own archive.
    if (same) {
      writeIfChanged(directory / kBuildFile,
                     storeBuildFile("nix_built",
                                    absl::StrCat(", archive = \"//",
                                                 built->second.package, ":",
                                                 built->second.target, "\"")));
      writeIfChanged(directory / kStoreDigestFile, built->second.digest + "\n");
      fs::remove(directory / kStoreArchiveFile);
      ++origins[Origin::Built];
      continue;
    }

    // The cache's archive.
    if (narinfo) {
      const auto repository = absl::StrCat(kRepositoryPrefix, storeHash(path));
      writeIfChanged(
          directory / kBuildFile,
          storeBuildFile("nix_fetched",
                         absl::StrCat(", src = \"@", repository,
                                      "//file\", compression = \"",
                                      narinfo->compression, "\", sha256 = \"",
                                      narinfo->archiveDigest, "\"")));
      writeIfChanged(directory / kStoreDigestFile,
                     narinfo->archiveDigest + "\n");
      fs::remove(directory / kStoreArchiveFile);
      fetched.emplace(repository, *narinfo);
      ++origins[Origin::Fetched];
      continue;
    }

    // This machine's copy, packed into the workspace. An archive that is
    // already there with its digest is the path's: a store path does not
    // change.
    const auto archive = directory / kStoreArchiveFile;
    if (!fs::exists(archive) || !fs::exists(directory / kStoreDigestFile)) {
      if (!fs::exists(fs::symlink_status(path))) {
        missing.push_back(path);
        continue;
      }
      fs::create_directories(directory);
      execute({std::string(kNixStore), "--dump", path}, {}, archive);
      writeBytes(directory / kStoreDigestFile, digest(archive) + "\n");
    }
    writeIfChanged(directory / kBuildFile, storeBuildFile("nix_source", ""));
    ++origins[Origin::Kept];
  }
  check(missing.empty(),
        absl::StrCat("no package builds these store paths, ", cache,
                     " does not have them and neither does this machine's "
                     "store:\n  ",
                     absl::StrJoin(missing, "\n  ")));

  // A store path nothing reads any more has no package.
  if (fs::is_directory(storeDirectory)) {
    std::vector<fs::path> stale;
    for (const auto &entry : fs::directory_iterator(storeDirectory)) {
      if (!wanted.contains(
              absl::StrCat("/nix/store/", entry.path().filename().string()))) {
        stale.push_back(entry.path());
      }
    }
    for (const auto &directory : stale) {
      removeTree(directory);
    }
  }

  // The repositories that fetch from the cache.
  std::string module = absl::StrCat(
      kGeneratedLine,
      "http_file = use_repo_rule(\"@bazel_tools//tools/build_defs/repo:"
      "http.bzl\", \"http_file\")\n");
  for (const auto &[repository, narinfo] : fetched) {
    absl::StrAppend(&module, "\nhttp_file(\n    name = \"", repository,
                    "\",\n    sha256 = \"", narinfo.fileDigest,
                    "\",\n    urls = [\"", cache, "/", narinfo.url, "\"],\n)\n");
  }
  writeIfChanged(workspace / kModuleFile, module);
  writeIfChanged(workspace / kSettingsFile,
                 absl::StrCat(kGeneratedLine, kSettings));

  // An alias for each attribute whose package is in the workspace.
  std::string root(kGeneratedLine);
  if (!attributes.empty()) {
    static const std::regex allowed{std::string(kAliasName)};
    for (const std::string_view line :
         absl::StrSplit(readBytes(attributes), '\n', absl::SkipEmpty())) {
      const std::pair<std::string, std::string> pair =
          absl::StrSplit(line, absl::MaxSplits(' ', 1));
      if (!std::regex_match(pair.first, allowed) ||
          !packages.contains(pair.second)) {
        continue;
      }
      absl::StrAppend(&root, "alias(name = \"", pair.first, "\", actual = \"//",
                      kPackagesDirectory, "/", pair.second, ":", kOutputsTarget,
                      "\")\n");
    }
  }
  writeIfChanged(workspace / kBuildFile, root);

  // Say where the store paths come from.
  llvm::outs() << counted(packages.size(), "package", "packages") << ", "
               << counted(wanted.size(), "store path", "store paths") << "\n"
               << "  " << origins[Origin::Built]
               << " built by a package of the workspace\n"
               << "  " << origins[Origin::Fetched] << " fetched from " << cache
               << "\n"
               << "  " << origins[Origin::Kept]
               << " kept as an archive in the workspace\n";
  if (differing > 0) {
    llvm::outs() << counted(differing, "output differs", "outputs differ")
                 << " from the cache's, which is what other builds read\n";
  }
}

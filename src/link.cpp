// Where a workspace keeps what a binary cache said of each store path: a
// narinfo file under the path's hash, or an empty marker when the cache
// does not have the path. A path is asked for once.
constexpr std::string_view kNarinfoDirectory = "narinfo";
constexpr std::string_view kNarinfoExtension = ".narinfo";
constexpr std::string_view kAbsentExtension = ".absent";

// The fields of a narinfo file that `link` reads, and what separates a
// field's name from its value.
constexpr std::string_view kUrlField = "URL";
constexpr std::string_view kCompressionField = "Compression";
constexpr std::string_view kFileHashField = "FileHash";
constexpr std::string_view kArchiveHashField = "NarHash";
constexpr std::string_view kFieldEnd = ": ";

// How Nix writes a SHA-256: the algorithm, then the digest in hex or in
// Nix's base 32, which are told apart by their length.
constexpr std::string_view kDigestPrefix = "sha256:";
constexpr size_t kHexDigestLength = 64;
constexpr size_t kBase32DigestLength = 52;
constexpr std::string_view kBase32Digits = "0123456789abcdfghijklmnpqrsvwxyz";
constexpr unsigned kBitsPerDigit = 5;
constexpr unsigned kBitsPerByte = 8;
constexpr unsigned kDigitMask = 0x1f;

// The length of the hash a store path's name starts with.
constexpr size_t kStoreHashLength = 32;

// What curl is asked to print: the status of the answer. A cache says
// 404 for a path it does not have, and one kept in a bucket can say 403.
constexpr std::string_view kStatusFormat = "%{http_code}";
constexpr std::string_view kFound = "200";
constexpr std::string_view kNotFound[] = {"404", "403"};

// The files `link` writes at the root of a workspace.
constexpr std::string_view kBuildFile = "BUILD.bazel";
constexpr std::string_view kModuleFile = "MODULE.bazel";
constexpr std::string_view kSettingsFile = ".bazelrc";
constexpr std::string_view kGeneratedLine = "# Generated by genrulify link.\n";

// The name of the repository that fetches a store path, before the
// path's hash.
constexpr std::string_view kRepositoryPrefix = "nar_";

// The names a root alias can have. An attribute with any other character
// is left out.
constexpr std::string_view kAliasName = "[A-Za-z0-9_.+-]+";

// A rule unpacks the store paths it reads below this directory, which
// the sandbox script names, once for all rules. Bazel's own sandbox has
// to let the rule write there.
constexpr std::string_view kSettings =
    "# A rule unpacks the store paths it reads below /var/tmp, once for\n"
    "# every rule that reads them.\n"
    "build --sandbox_writable_path=/var/tmp\n";

// What a binary cache says of a store path, with both digests in hex.
struct Narinfo {
  std::string url;
  std::string compression;
  std::string fileDigest;
  std::string archiveDigest;
};

// The output of a package that is a store path: the package, the target
// that builds the path's archive, and the digest the archive has.
struct Built {
  std::string package;
  std::string target;
  std::string digest;
};

// Where a store path's archive comes from.
enum class Origin { Built, Fetched, Kept };

// Bytes from Nix's base 32, which writes the last five bits first.
std::string fromBase32(std::string_view text) {
  std::string bytes(text.size() * kBitsPerDigit / kBitsPerByte, '\0');
  for (size_t index = 0; index < text.size(); ++index) {
    const auto digit = kBase32Digits.find(text[text.size() - index - 1]);
    check(digit != std::string_view::npos,
          absl::StrCat("not a digest in base 32: ", text));
    const size_t bit = index * kBitsPerDigit;
    const size_t byte = bit / kBitsPerByte;
    const unsigned shift = bit % kBitsPerByte;
    bytes[byte] = static_cast<char>(static_cast<uint8_t>(bytes[byte]) |
                                    static_cast<uint8_t>(digit << shift));
    const unsigned carry = static_cast<unsigned>(digit) >>
                           (kBitsPerByte - shift);
    if (byte + 1 < bytes.size()) {
      bytes[byte + 1] = static_cast<char>(
          static_cast<uint8_t>(bytes[byte + 1]) | static_cast<uint8_t>(carry));
    }
  }
  return bytes;
}

// A SHA-256 in hex from any of the ways Nix writes one.
std::string hexDigest(std::string_view value) {
  if (value.starts_with(kDigestPrefix)) {
    value.remove_prefix(kDigestPrefix.size());
  }
  if (value.size() == kHexDigestLength) {
    return std::string(value);
  }
  check(value.size() == kBase32DigestLength,
        absl::StrCat("not a SHA-256 digest: ", value));
  return toHex(fromBase32(value));
}

// The hash a store path's name starts with.
std::string storeHash(const std::string &path) {
  const auto name = storeName(path);
  check(name.size() > kStoreHashLength && name[kStoreHashLength] == '-',
        absl::StrCat("not a store path: ", path));
  return name.substr(0, kStoreHashLength);
}

// Writes a file unless the file already has the bytes, so that a second
// link of the same workspace changes nothing a build would notice.
void writeIfChanged(const fs::path &file, std::string_view bytes) {
  if (fs::exists(file) && readBytes(file) == bytes) {
    return;
  }
  fs::create_directories(file.parent_path());
  writeBytes(file, bytes);
}

// What the cache said of a store path, from the workspace's copy of the
// answer. Unset when the cache does not have the path.
std::optional<Narinfo> readNarinfo(const fs::path &directory,
                                   const std::string &path) {
  const auto file =
      directory / absl::StrCat(storeHash(path), kNarinfoExtension);
  if (!fs::exists(file)) {
    return std::nullopt;
  }
  std::map<std::string, std::string> fields;
  for (const std::string_view line :
       absl::StrSplit(readBytes(file), '\n', absl::SkipEmpty())) {
    const auto end = line.find(kFieldEnd);
    if (end != std::string_view::npos) {
      fields.emplace(line.substr(0, end), line.substr(end + kFieldEnd.size()));
    }
  }
  const auto field = [&](std::string_view name) {
    const auto found = fields.find(std::string(name));
    check(found != fields.end(),
          absl::StrCat(file.string(), " has no ", name));
    return found->second;
  };
  return Narinfo{field(kUrlField), field(kCompressionField),
                 hexDigest(field(kFileHashField)),
                 hexDigest(field(kArchiveHashField))};
}

// Asks the cache for every store path the workspace has no answer for
// yet, and keeps each answer.
void fetchNarinfos(const fs::path &directory, const std::string &cache,
                   const std::set<std::string> &paths) {
  std::vector<std::string> unknown;
  for (const auto &path : paths) {
    const auto hash = storeHash(path);
    if (!fs::exists(directory / absl::StrCat(hash, kNarinfoExtension)) &&
        !fs::exists(directory / absl::StrCat(hash, kAbsentExtension))) {
      unknown.push_back(hash);
    }
  }
  fs::create_directories(directory);
  parallelFor(unknown.size(), [&](size_t index) {
    const auto &hash = unknown[index];
    const auto file = directory / absl::StrCat(hash, kNarinfoExtension);
    const auto partial = directory / absl::StrCat(hash, ".partial");
    const auto status =
        capture({std::string(kCurl), "--silent", "--location", "--output",
                 partial.string(), "--write-out", std::string(kStatusFormat),
                 absl::StrCat(cache, "/", hash, kNarinfoExtension)});
    if (status == kFound) {
      fs::rename(partial, file);
      return;
    }
    fs::remove(partial);
    check(std::ranges::find(kNotFound, status) != std::end(kNotFound),
          absl::StrCat(cache, " answered ", status, " for ", hash,
                       kNarinfoExtension));
    writeBytes(directory / absl::StrCat(hash, kAbsentExtension), "");
  });
}

// The build file of a store path's package: one call of the rule for
// where the archive comes from.
std::string storeBuildFile(std::string_view rule, std::string_view arguments) {
  return absl::StrCat(kGeneratedLine, "load(\"//", kSharedDirectory, ":",
                      kSharedRulesFile, "\", \"", rule, "\")\n\n", rule,
                      "(name = \"", kStorePathTarget, "\"", arguments, ")\n");
}

// "1 output differs" or "3 outputs differ".
std::string counted(size_t count, std::string_view one, std::string_view many) {
  return absl::StrCat(count, " ", count == 1 ? one : many);
}
